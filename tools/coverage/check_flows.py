"""User flow coverage report and guard.

Reads coverage/flows.json (written by tests/flow_coverage.py during a test run) and:
- prints which flows are proven on which devices, and names the gaps
- writes docs/user-flows.md, the flow list with the tests that prove each one
- fails if a flow-device pair in tools/coverage/flow_baseline.json lost its test

Usage, after a full test run:
    python tools/coverage/check_flows.py            # report + guard (CI)
    python tools/coverage/check_flows.py --update   # also accept today's coverage as the baseline
"""

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULT = ROOT / "coverage" / "flows.json"
BASELINE = ROOT / "tools" / "coverage" / "flow_baseline.json"
DOC = ROOT / "docs" / "user-flows.md"
DEVICES = ("desktop", "phone", "tablet")


def covered_pairs(flows):
    return sorted(f"{flow}/{device}" for flow, info in flows.items() for device in DEVICES if info["tests"][device])


def table(flows):
    lines = ["| Flow | Desktop | Phone | Tablet |", "|---|---|---|---|"]
    for info in flows.values():
        marks = ["✅ " + str(len(info["tests"][d])) if info["tests"][d] else "—" for d in DEVICES]
        lines.append(f"| {info['name']} | " + " | ".join(marks) + " |")
    return lines


def gaps(flows):
    return [
        f"- {info['name']}: " + ", ".join(d for d in DEVICES if not info["tests"][d])
        for info in flows.values()
        if any(not info["tests"][d] for d in DEVICES)
    ]


def summary(flows):
    pairs = covered_pairs(flows)
    total = len(flows) * len(DEVICES)
    full = sum(all(info["tests"][d] for d in DEVICES) for info in flows.values())
    lines = [
        "## User flow coverage",
        "",
        f"**{len(pairs)} of {total} flow-device pairs proven ({100 * len(pairs) / total:.0f}%).** "
        f"{full} of {len(flows)} flows are proven on every device.",
        "",
        *table(flows),
    ]
    missing = gaps(flows)
    if missing:
        lines += ["", "### Gaps (no passing test yet)", "", *missing]
    return lines


def doc(flows):
    lines = [
        "# User flows",
        "",
        "Every user flow in Sweat Equity, with the browser tests that prove it on each device. "
        "Generated by `python tools/coverage/check_flows.py --update` from a full test run; "
        "the flow list itself is `tests/flows.toml`. Devices are Chromium at desktop size and "
        "Chromium's phone and tablet emulation with touch, not real devices.",
        "",
        *summary(flows)[2:],
        "",
        "## Tests behind each flow",
    ]
    for info in flows.values():
        lines += ["", f"### {info['name']}"]
        for device in DEVICES:
            tests = info["tests"][device]
            if tests:
                lines.append(f"- **{device.capitalize()}:** " + ", ".join(f"`{t}`" for t in tests))
            else:
                lines.append(f"- **{device.capitalize()}:** none yet")
    return "\n".join(lines) + "\n"


def main():
    if not RESULT.exists():
        sys.exit("No coverage/flows.json: run the full test suite first.")
    flows = json.loads(RESULT.read_text(encoding="utf-8"))["flows"]
    report = "\n".join(summary(flows))
    print(report)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a", encoding="utf-8") as out:
            out.write(report + "\n")

    pairs = covered_pairs(flows)
    if "--update" in sys.argv:
        BASELINE.write_text(json.dumps({"covered": pairs}, indent=2) + "\n", encoding="utf-8")
        DOC.write_text(doc(flows), encoding="utf-8", newline="\n")
        print(f"\nBaseline and {DOC.name} updated.")
        return

    baseline = json.loads(BASELINE.read_text(encoding="utf-8"))["covered"]
    lost = sorted(set(baseline) - set(pairs))
    gained = sorted(set(pairs) - set(baseline))
    if gained:
        print("\nNewly covered (refresh with --update): " + ", ".join(gained))
    if lost:
        sys.exit("\nFlow coverage dropped. No passing test proves: " + ", ".join(lost))
    print("\nFlow coverage guard passed.")


if __name__ == "__main__":
    main()
